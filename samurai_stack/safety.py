"""Small, deliberately restrictive filesystem and process primitives."""
from __future__ import annotations

import hashlib
import ipaddress
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import subprocess
import tempfile
from typing import Any
import uuid


class SafetyError(RuntimeError):
    pass


def digest(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def run(argv, *, timeout=120, input=None):
    """Never echo command output: application errors can contain credentials."""
    try:
        result = subprocess.run(list(map(str, argv)), text=True, input=input, capture_output=True, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise SafetyError(f"{argv[0]} could not run or timed out; check installation and private local logs") from exc
    if result.returncode:
        raise SafetyError(f"{argv[0]} failed (exit {result.returncode}); no service configuration was accepted")
    return result


def absolute_path(value, label):
    if not isinstance(value, str) or not value.startswith("/") or "\x00" in value or "\n" in value:
        raise SafetyError(f"{label} must be an absolute Linux path")
    path = PurePosixPath(value)
    if ".." in path.parts or str(path) != value or re.search(r"[\s$`\\]", value):
        raise SafetyError(f"{label} must be normalized, without whitespace or shell/Compose substitutions")
    if len(path.parts) < 3 or value in {"/var/lib", "/var/log", "/etc/ssh", "/dev/shm"}:
        raise SafetyError(f"{label} must name a dedicated subdirectory, not a system root")
    if path.parts[1] in {"proc", "sys", "dev", "etc", "boot", "bin", "sbin", "lib", "usr"}:
        raise SafetyError(f"{label} cannot be inside a system directory")
    return path


def no_symlinks(path):
    path = Path(path)
    for candidate in reversed([path, *path.parents]):
        if candidate.is_symlink():
            raise SafetyError(f"Refusing symbolic link in managed path: {candidate}")
    return path


def contained(path, root):
    path, root = Path(path), Path(root)
    no_symlinks(root)
    no_symlinks(path)
    try:
        path.relative_to(root)
    except ValueError as exc:
        raise SafetyError("Managed path escaped its declared root") from exc
    return path


def private_read(path):
    path = no_symlinks(path)
    info = path.stat()
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise SafetyError(f"Private file must be a regular file without hard links: {path.name}")
    if os.name == "posix" and info.st_mode & 0o077:
        raise SafetyError(f"Private file is accessible to other users; set mode 600: {path.name}")
    return path.read_text(encoding="utf-8")


def atomic_write(path, content, *, replace=False, mode=0o600):
    path = no_symlinks(path)
    no_symlinks(path.parent)
    if path.exists() and not replace:
        raise SafetyError(f"Refusing to overwrite existing file: {path.name}")
    fd, temp = tempfile.mkstemp(prefix=".samurai-", dir=path.parent)
    try:
        os.chmod(temp, mode)
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        if replace:
            os.replace(temp, path)
        else:
            # Hard-link publication provides no-clobber semantics, unlike rename.
            os.link(temp, path)
            os.unlink(temp)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def write_json(path, value, **kwargs):
    atomic_write(path, json.dumps(value, indent=2, sort_keys=True) + "\n", **kwargs)


def load_config(path):
    try:
        config = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        raise SafetyError("Configuration is missing or not valid JSON") from exc
    validate_config(config)
    return config


def validate_config(c):
    if c.get("schema_version") != 1:
        raise SafetyError("Unsupported configuration schema_version")
    try:
        uuid.UUID(c["deployment_id"])
    except (KeyError, ValueError, TypeError, AttributeError) as exc:
        raise SafetyError("deployment_id must be a UUID generated by init") from exc
    if not re.fullmatch(r"[a-z][a-z0-9-]{1,39}", c.get("deployment_name", "")):
        raise SafetyError("deployment_name must be 2-40 lowercase letters, digits or hyphens")
    install = absolute_path(c.get("install_root"), "install_root")
    data = absolute_path(c.get("storage", {}).get("data_root"), "storage.data_root")
    if install == data or install in data.parents or data in install.parents:
        raise SafetyError("Application storage and media storage must not overlap")
    for key in ["puid", "pgid"]:
        if type(c.get(key)) is not int or not 1 <= c[key] <= 2147483647:
            raise SafetyError(f"{key} must be a non-root numeric ID")
    for label, value in [("bind_address", c.get("bind_address")), *c.get("hosts", {}).items()]:
        try:
            ip = ipaddress.ip_address(value)
        except (ValueError, TypeError) as exc:
            raise SafetyError(f"{label} must be an explicit IPv4 LAN address") from exc
        if ip.version != 4 or not (ip.is_private or ip.is_loopback) or ip.is_unspecified or ip.is_multicast or ip.is_link_local:
            raise SafetyError(f"{label} cannot publish services on all interfaces or a public address")
    roles = {"media", "torrent", "management", "photos", "music"}
    if set(c.get("hosts", {})) != roles:
        raise SafetyError("hosts must specify media, torrent, management, photos and music LAN addresses")
    if c.get("role", "all") not in roles | {"all"}:
        raise SafetyError("Unknown host role")
    if c.get("hardware", {}).get("acceleration", "cpu") not in {"cpu", "intel", "amd", "nvidia"}:
        raise SafetyError("Unsupported hardware acceleration choice")
    storage = c["storage"]
    if type(storage.get("allow_existing_contents", False)) is not bool:
        raise SafetyError("storage.allow_existing_contents must be a JSON boolean")
    if storage.get("mode") not in {"local", "nfs"}:
        raise SafetyError("storage.mode must be local or nfs")
    identity = storage.get("expected_mount", {})
    if not all(isinstance(identity.get(k), str) and identity[k] for k in ["target", "source", "fstype"]):
        raise SafetyError("An explicit expected_mount target, source and fstype is required")
    target = PurePosixPath(identity["target"])
    if not str(target).startswith("/") or ".." in target.parts or not (target == data or target in data.parents):
        raise SafetyError("Expected mount must contain data_root")
    if storage["mode"] == "nfs" and identity["fstype"] not in {"nfs", "nfs4"}:
        raise SafetyError("NFS mode requires an nfs or nfs4 mount identity")
    if storage["mode"] == "local" and identity["fstype"] not in {"ext4", "xfs", "btrfs", "zfs"}:
        raise SafetyError("Local data must use a supported Linux filesystem")
    if not isinstance(c.get("timezone"), str) or not re.fullmatch(r"[A-Za-z0-9_+/-]+", c["timezone"]):
        raise SafetyError("A valid IANA timezone name is required")
    if any(type(v) is not bool for v in c.get("features", {}).values()):
        raise SafetyError("Feature switches must be JSON booleans")
    if c.get("downloads", {}).get("prefer", "usenet") not in {"usenet", "torrents"}:
        raise SafetyError("downloads.prefer must be usenet or torrents")
    vpn = c.get("vpn", {})
    if type(vpn.get("port_forwarding", False)) is not bool:
        raise SafetyError("vpn.port_forwarding must be a JSON boolean")
    if vpn.get("provider") not in {"protonvpn", "mullvad", "custom"} or vpn.get("type") not in {"wireguard", "openvpn"}:
        raise SafetyError("Choose a supported VPN provider/protocol or custom configuration")
    if vpn.get("port_forwarding") and vpn["provider"] != "protonvpn":
        raise SafetyError("This release automates dynamic forwarding for Proton only; other providers work without forwarding")
    if vpn["provider"] == "mullvad" and vpn["type"] != "wireguard":
        raise SafetyError("Mullvad no longer supports OpenVPN; choose WireGuard")
    if vpn["provider"] == "mullvad" and not vpn.get("wireguard_addresses"):
        raise SafetyError("Mullvad requires its assigned wireguard_addresses")
    # Credentials belong in private files, never the site configuration.
    def check(value):
        if isinstance(value, dict):
            for k, v in value.items():
                if re.search(r"password|token|private_key|api_key", k, re.I) and v:
                    raise SafetyError("Do not put credentials in site JSON; use the secret command")
                check(v)
        elif isinstance(value, list):
            for v in value:
                check(v)
    check(c)
    return c
